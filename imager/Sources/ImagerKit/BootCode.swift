    /// The first sector of the disk: our code, a disk signature, one active partition of type 0x0C (FAT32, LBA).
    public static func mbr(diskSignature: UInt32, partitionStart: UInt32, partitionSectors: UInt32) -> Data {
        var d = Data(count: 512)
        d.put(mbrCode, at: 0)
        d.put32(diskSignature, at: 440)
        var e = Data(count: 16)
        e[0] = 0x80
        e.put(chs(partitionStart), at: 1)
        e[4] = 0x0C
        e.put(chs(partitionStart + partitionSectors - 1), at: 5)
        e.put32(partitionStart, at: 8)
        e.put32(partitionSectors, at: 12)
        d.replaceSubrange(446..<462, with: e)
        d[510] = 0x55
        d[511] = 0xAA
        return d
    }

    /// A sector's CHS address for the partition table, as BIOSes read it (255 heads, 63 sectors a track); past what
    /// CHS can say, the usual 1023/254/63.
    static func chs(_ lba: UInt32) -> [UInt8] {
        let perCylinder: UInt32 = 255 * 63
        let c = lba / perCylinder
        guard c <= 1023 else { return [0xFE, 0xFF, 0xFF] }
        let h = (lba / 63) % 255
        let s = lba % 63 + 1
        return [UInt8(h), UInt8(s) | UInt8((c >> 8) << 6), UInt8(c & 0xFF)]
    }

    /// The partition's first sector: the FAT32 BPB (Microsoft's FAT32 specification, version 1.03) around our code.
    public static func fat32BootSector(totalSectors: UInt32, sectorsPerCluster: UInt8, reservedSectors: UInt16,
                                       fatSectors: UInt32, hiddenSectors: UInt32, volumeID: UInt32, label: [UInt8],
                                       loader: (sector: Int64, count: Int64)?) -> Data {
        var d = Data(fat32Code)
        d.put(Array("MSWIN4.1".utf8), at: 3)
        d.put16(512, at: 11)
        d[13] = sectorsPerCluster
        d.put16(reservedSectors, at: 14)
        d[16] = 2                                   // FATs
        d.put16(0, at: 17)                          // root entries (none on FAT32)
        d.put16(0, at: 19)
        d[21] = 0xF8                                // a fixed disk
        d.put16(0, at: 22)
        d.put16(63, at: 24)                         // sectors a track
        d.put16(255, at: 26)                        // heads
        d.put32(hiddenSectors, at: 28)
        d.put32(totalSectors, at: 32)
        d.put32(fatSectors, at: 36)
        d.put16(0, at: 40)                          // both FATs kept the same
        d.put16(0, at: 42)                          // version 0.0
        d.put32(2, at: 44)                          // the root folder's cluster
        d.put16(1, at: 48)                          // FSInfo
        d.put16(6, at: 50)                          // the backup boot sector
        d[64] = 0x80
        d[66] = 0x29
        d.put32(volumeID, at: 67)
        d.put(Array(label.prefix(11)) + Array(repeating: 0x20, count: max(0, 11 - label.count)), at: 71)
        d.put(Array("FAT32   ".utf8), at: 82)
        if let l = loader {
            d.put32(UInt32(l.sector), at: loaderSectorOffset)
            d.put16(UInt16(l.count), at: loaderCountOffset)
        }
        return d
    }
